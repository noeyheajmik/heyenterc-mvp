export function regionSelection(province = '', district = '') {
  const parent = REGIONS.find(p => p.id === province);
  if (!parent) return { province: '', district: '', region: '전국' };
  const child = parent.districts.find(d => d.id === district);
  return { province: parent.id, district: child?.id || '', region: parent.name + (child ? ' ' + child.name : ' 전체') };
}
